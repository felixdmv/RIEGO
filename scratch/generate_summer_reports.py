import os
import shutil
import subprocess

base_path = r"C:\Users\fdemiguel\OneDrive - Universidad de Burgos\Documentos\RIEGO"
artifact_dir = r"C:\Users\fdemiguel\.gemini\antigravity-cli\brain\1bd7f3e1-c449-41ed-b6db-fe0ef5a2e5a0"

dates_mapping = {
    "2024-06-01": "Informe_Inicio_Temporada_2024-06-01.pdf",
    "2024-06-26": "Informe_Lluvias_Previstas_2024-06-26.pdf",
    "2024-07-20": "Informe_Medio_Verano_2024-07-20.pdf",
    "2024-08-10": "Informe_Pico_Estres_2024-08-10.pdf"
}

python_exe = r"C:\Users\fdemiguel\AppData\Local\anaconda3\envs\agro_ft\python.exe"
script_path = os.path.join(base_path, "run_pipeline.py")

for date, output_name in dates_mapping.items():
    print(f"\n>>> Generating report for date: {date}...")
    try:
        # Run report generation
        cmd = [python_exe, script_path, "--mode", "report", "--date", date]
        result = subprocess.run(cmd, cwd=base_path, capture_output=True, text=True, check=True)
        print(f"  Finished: {result.stdout.strip().splitlines()[-1] if result.stdout else 'Success'}")
        
        # Source filename generated by run_pipeline.py
        src_name = f"Informe_Final_{date}.pdf"
        src_path = os.path.join(base_path, src_name)
        
        if os.path.exists(src_path):
            # Copy to workspace with descriptive name
            dst_desc_workspace = os.path.join(base_path, output_name)
            shutil.copy2(src_path, dst_desc_workspace)
            print(f"  Saved in workspace as: {output_name}")
            
            # Copy to artifact folder
            dst_artifact = os.path.join(artifact_dir, output_name)
            shutil.copy2(src_path, dst_artifact)
            print(f"  Copied to artifacts folder: {output_name}")
            
            # Clean up the original raw output
            os.remove(src_path)
        else:
            print(f"  Error: {src_name} was not found after execution.")
    except Exception as e:
        print(f"  Failed for {date}: {e}")

print("\nBatch generation complete!")

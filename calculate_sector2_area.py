# Flat projection setup
lat_avg = sum(c[1] for c in coords_s2) / len(coords_s2)
lat_to_m = 111132.0
lon_to_m = 111132.0 * math.cos(math.radians(lat_avg))

# Convert to meters relative to centroid or first point
x = [c[0] * lon_to_m for c in coords_s2]
y = [c[1] * lat_to_m for c in coords_s2]

# Shoelace formula
n = len(x)
area = 0.0
for i in range(n):
    j = (i + 1) % n
    area += x[i] * y[j]
    area -= x[j] * y[i]
area_m2 = abs(area) / 2.0

print("--- SECTOR 2 POLYGON AREA ---")
print(f"Area in m2: {area_m2:.2f} m2")
print(f"Area in ha: {area_m2 / 10000.0:.4f} ha")

# Flow rate from Excel
